#!/usr/bin/env bash
set -euo pipefail

# Regenerate THIRD_PARTY_LICENSES.md (repo root): every third-party crate compiled into the
# firmware and the host tools, with version, license and authors. Run after changing dependencies.
# Needs: cargo, python3. Works offline once dependencies are fetched.

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  echo "Usage: firmware/tools/third_party_licenses.sh   (run from anywhere; writes THIRD_PARTY_LICENSES.md in the repo root)"
  exit 0
fi

FW_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$(cd "$FW_ROOT/.." && pwd)/THIRD_PARTY_LICENSES.md"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
(cd "$FW_ROOT/kb_firmware" && cargo metadata --offline --format-version 1 --filter-platform thumbv7em-none-eabihf) > "$TMP/fw.json"
(cd "$FW_ROOT/crs_tools" && cargo metadata --offline --format-version 1 --filter-platform x86_64-unknown-linux-gnu) > "$TMP/tools.json"

python3 - "$OUT" "$TMP/fw.json" "$TMP/tools.json" <<'PY'
import json, sys

def crates(path):
    with open(path) as f:
        m = json.load(f)
    used = {n["id"] for n in m["resolve"]["nodes"]}
    out = []
    for p in m["packages"]:
        if p["id"] in used and p["source"]:  # third-party only (skip our path crates)
            authors = ", ".join(a.split("<")[0].strip() for a in p.get("authors", [])) or "—"
            out.append((p["name"], p["version"], p.get("license") or "see crate", authors,
                        p.get("repository") or ""))
    return sorted(out)

def table(rows):
    lines = ["| Crate | Version | License | Authors / copyright holders |", "|---|---|---|---|"]
    for name, ver, lic, authors, repo in rows:
        crate = f"[{name}]({repo})" if repo else name
        lines.append(f"| {crate} | {ver} | {lic} | {authors} |")
    return "\n".join(lines)

fw = crates(sys.argv[2])
tools = crates(sys.argv[3])

text = f"""# Third-party licenses

<!-- Generated by firmware/tools/third_party_licenses.sh — do not edit by hand. -->

KB-E2B6 (firmware, host tools and web configurator) is licensed under MIT OR Apache-2.0
(`LICENSE-MIT`, `LICENSE-APACHE`). It is built from the open-source crates listed below, each under
its own license (all permissive: MIT, Apache-2.0, and alternatives such as Zlib, BSD-2-Clause,
Unlicense, Unicode-3.0). The full text of the MIT and Apache-2.0 licenses is in the two LICENSE
files in this repository; the copyright notices belong to the authors listed for each crate.

The web configurator (`web_config/`) uses no third-party code.

## Firmware — {len(fw)} crates (runtime code in every board + build-time tools)

{table(fw)}

## Host tools (`crs-pack`, Linux build) — {len(tools)} crates (incl. build-time tools)

{table(tools)}
"""
with open(sys.argv[1], "w") as f:
    f.write(text)
print(f"ok: wrote {sys.argv[1]} ({len(fw)} firmware crates, {len(tools)} host-tool crates)")
PY
